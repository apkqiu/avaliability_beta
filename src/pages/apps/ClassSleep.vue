<template>

    <div style="all:initial">


        <div id="game-container">
            <h1>上课睡觉模拟器</h1>

            <div id="start-screen">
                <div class="selection-panel">
                    <div class="option-group">
                        <h3>选择难度</h3>

                        <div class="option selected" data-difficulty="easy">简单</div>

                        <div class="option" data-difficulty="normal">普通</div>

                        <div class="option" data-difficulty="hard">困难</div>
                    </div>

                    <div class="option-group">
                        <h3>选择状态</h3>

                        <div class="option selected" data-status="normal">普通</div>

                        <div class="option" data-status="stay-up">熬夜</div>

                        <div class="option" data-status="very-sleepy">极困</div>
                    </div>
                </div>

                <a id="start-btn" class="btn">开始游戏</a>
            </div>

            <div id="game-screen">
                <p id="condition">状态</p>

                <p id="sleep-time-display"></p>

                <p id="status-display"></p>

                <p id="quote-display">初始化</p>

                <div id="sit" class="action-btn">端坐</div>

                <div id="sleep" class="action-btn">睡眠</div>

                <div id="teacher-image"><img src="@/static/img/loading.gif" alt="老师" /></div>
            </div>

            <div id="game-over">
                <h2>游戏结束</h2>

                <p id="game-over-message"></p>

                <p id="score-display"></p>

                <p id="high-score-display"></p>

                <a id="play-again-btn" class="btn">再玩一次</a>
            </div>
        </div>

        <div id="errors"></div>
    </div>
