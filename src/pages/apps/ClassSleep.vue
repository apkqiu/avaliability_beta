<script setup>
// 游戏配置
import { onMounted } from "vue";
definePage({
    meta: {
        title: "上课睡觉模拟器"
    },
})
const GAME_CONFIG = {
    difficulties: {
        easy: { name: '简单', teacherChangeMin: 2000, teacherChangeMax: 4000 },

        normal: { name: '普通', teacherChangeMin: 1500, teacherChangeMax: 3000 },

        hard: { name: '困难', teacherChangeMin: 1000, teacherChangeMax: 2000 },
    },

    statuses: {
        normal: { name: '普通', forceSleepTime: 0 },

        'stay-up': { name: '熬夜', forceSleepTime: 30000 },

        'very-sleepy': { name: '极困', forceSleepTime: 10000 },
    },

    quotes: [
        '我客气你当福气啊',

        'Underline.',
        'Underline the whole sentence.',
        '来',
        '已知∠BA=200°',

        '表达了作者的喜爱和赞美之情。',
        '闲敲棋子落灯花。',
        '进了一班，不等于进了保险箱',

        '死读书，读死书，读书死',
        '你有没有感觉这道题像在考语文？',
        '咬文嚼字',

        'ok挠',
        '表达了作者的思乡之情',
        'Underline the phrase.',
        '这题错的站起来',

        '做一张基础卷',
    ],
    images: {
        sit: await import('@/static/img/sit.jpeg'),
        sleep: await import('@/static/img/sleep.jpeg'),
    },
};
// 游戏状态
let gameState = {
    difficulty: 'easy',

    status: 'normal',

    isSleeping: false,
    totalSleepTime: 0,
    currentSleepStart: 0,

    teacherIsLooking: true,

    lastWakeTime: 0,
    gameIntervals: [],
    selectedDifficulty: 'easy',
    selectedStatus: 'normal',
};
// 初始化游戏
function initGame() {
    setupOptionSelection();

    document.getElementById('start-btn').addEventListener('click', startGame);

    document.getElementById('play-again-btn').addEventListener('click', resetGame);
}

// 设置选项选择

function setupOptionSelection() {
    // 难度选择

    document.querySelectorAll('[data-difficulty]').forEach((option) => {
        option.addEventListener('click', function () {
            document.querySelectorAll('[data-difficulty]').forEach((opt) => opt.classList.remove('selected'));
            this.classList.add('selected');
            gameState.selectedDifficulty = this.getAttribute('data-difficulty');
        });
    });

    // 状态选择
    document.querySelectorAll('[data-status]').forEach((option) => {
        option.addEventListener('click', function () {
            document.querySelectorAll('[data-status]').forEach((opt) => opt.classList.remove('selected'));
            this.classList.add('selected');
            gameState.selectedStatus = this.getAttribute('data-status');
        });
    });
}

// 开始游戏
function startGame() {
    gameState.difficulty = gameState.selectedDifficulty;
    gameState.status = gameState.selectedStatus;

    document.getElementById('start-screen').style.display = 'none';
    document.getElementById('game-screen').style.display = 'block';
    document.getElementById('game-over').style.display = 'none';

    resetGameState();
    setupGame();
}

// 重置游戏状态
function resetGameState() {
    gameState.isSleeping = false;
    gameState.totalSleepTime = 0;
    gameState.currentSleepStart = 0;
    gameState.teacherIsLooking = true;
    gameState.lastWakeTime = performance.now();
    gameState.gameIntervals.forEach((interval) => clearInterval(interval));
    gameState.gameIntervals = [];
}

// 设置游戏
function setupGame() {
    // 更新状态显示

    document.getElementById('status-display').textContent = `难度: ${GAME_CONFIG.difficulties[gameState.difficulty].name} | 状态: ${GAME_CONFIG.statuses[gameState.status].name
        }`;

    // 设置事件监听
    document.getElementById('sit').addEventListener('mouseover', wakeUp);
    document.getElementById('sleep').addEventListener('mouseover', fallAsleep);

    // 开始游戏循环
    gameState.gameIntervals.push(setInterval(updateGame, 100));
    gameState.gameIntervals.push(setInterval(changeTeacherState, getRandomTeacherTime()));
    gameState.gameIntervals.push(setInterval(showRandomQuote, 5000));

    // 如果状态需要强制睡眠，设置检查
    if (GAME_CONFIG.statuses[gameState.status].forceSleepTime > 0) {
        gameState.gameIntervals.push(setInterval(checkForceSleep, 1000));
    }
}

// 游戏主循环
function updateGame() {
    updateSleepTime();
    checkGameOver();
}

// 更新睡眠时间显示
function updateSleepTime() {
    if (gameState.isSleeping) {
        const currentTime = performance.now();
        const currentSleepDuration = (currentTime - gameState.currentSleepStart) / 1000;
        document.getElementById('sleep-time-display').textContent = `本次睡眠时间：${currentSleepDuration.toFixed(1)}秒`;
        document.getElementById('condition').textContent = '正在睡眠';
    } else {
        document.getElementById('sleep-time-display').textContent = `统共睡眠时间：${(gameState.totalSleepTime / 1000).toFixed(1)}秒`;
        document.getElementById('condition').textContent = '正在端坐';
    }
}

// 检查是否需要强制睡眠
function checkForceSleep() {
    if (!gameState.isSleeping) {
        const currentTime = performance.now();
        const awakeTime = currentTime - gameState.lastWakeTime;
        const forceSleepTime = GAME_CONFIG.statuses[gameState.status].forceSleepTime;

        if (awakeTime >= forceSleepTime) {
            fallAsleep();
            document.getElementById('quote-display').textContent = '太困了...坚持不住了...zzz';
        } else {
            const remainingTime = Math.ceil((forceSleepTime - awakeTime) / 1000);
            if (remainingTime <= 5) {
                document.getElementById('quote-display').textContent = `好困啊...还能坚持${remainingTime}秒...`;
            }
        }
    }
}

// 检查游戏结束条件
function checkGameOver() {
    if (gameState.isSleeping && !gameState.teacherIsLooking) {
        endGame();
    }
}

// 游戏结束
function endGame() {
    gameState.gameIntervals.forEach((interval) => clearInterval(interval));

    const score = gameState.totalSleepTime / 1000;
    let highestScore = parseFloat(localStorage.getItem('ClassSleepHighestRecord') || '0');

    if (score > highestScore) {
        highestScore = score;
        localStorage.setItem('ClassSleepHighestRecord', highestScore.toString());
    }

    document.getElementById('game-screen').style.display = 'none';
    document.getElementById('game-over').style.display = 'block';
    document.getElementById('game-over-message').textContent = '我对你客气，你把我当福气是不是';
    document.getElementById('score-display').textContent = `成绩：${score.toFixed(1)}秒`;
    document.getElementById('high-score-display').textContent = `最高纪录：${highestScore.toFixed(1)}秒`;
}

// 老师状态变化
function changeTeacherState() {
    gameState.teacherIsLooking = !gameState.teacherIsLooking;
    document.getElementById('teacher-image').innerHTML = `<img src="${gameState.teacherIsLooking ? GAME_CONFIG.images.sit : GAME_CONFIG.images.sleep
        }" alt="${gameState.teacherIsLooking ? '老师转头' : '老师看你'}">`;

    // 更新老师状态变化间隔
    clearInterval(gameState.gameIntervals[1]);
    gameState.gameIntervals[1] = setInterval(changeTeacherState, getRandomTeacherTime());
}

// 获取随机的老师状态变化时间
function getRandomTeacherTime() {
    const diff = GAME_CONFIG.difficulties[gameState.difficulty];
    return Math.random() * (diff.teacherChangeMax - diff.teacherChangeMin) + diff.teacherChangeMin;
}

// 显示随机语录
function showRandomQuote() {
    if (!gameState.isSleeping) {
        const randomQuote = GAME_CONFIG.quotes[Math.floor(Math.random() * GAME_CONFIG.quotes.length)];
        document.getElementById('quote-display').textContent = randomQuote;
    }
}

// 玩家入睡
function fallAsleep() {
    if (gameState.isSleeping) return;

    gameState.isSleeping = true;
    gameState.currentSleepStart = performance.now();
}

// 玩家醒来
function wakeUp() {
    if (!gameState.isSleeping) return;

    gameState.isSleeping = false;
    const wakeTime = performance.now();
    gameState.totalSleepTime += wakeTime - gameState.currentSleepStart;
    gameState.lastWakeTime = wakeTime;
}

// 重置游戏
function resetGame() {
    document.getElementById('game-over').style.display = 'none';
    startGame();
}

// 初始化游戏
onMounted(initGame)

// 全局错误处理
window.addEventListener('error', function (event) {
    const errorMsg = `\n错误：${event.message} (在第${event.lineno}行)`;
    document.getElementById('errors').textContent += errorMsg;
    console.error(event.error);
});
</script>